const hasHan = (s) => /[\u3400-\u9fff\u3000-\u303f\uff00-\uffef]/.test(s);

/** 剥离标题前缀：emoji、装饰符、数字序号（`1. `、`步骤 1: `、`#5 `）、全角空格等 */
function stripPrefix(text) {
  return text
    .replace(
      /^[\s\u200d]*[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}\u{FE0F}\u2705\u274C\u2757\u2753\u2757\u26A0]/gu,
      '',
    )
    .replace(/^[\s\u200d✅❌⭐️📋🚀]+/, '')
    .replace(/^#{0,2}\s*\d+(\.\d+)*[.、:：\s]\s*/, '')
    .replace(/^步骤\s*\d+\s*[:：]\s*/, '')
    .replace(/^[-–—\s]+/, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/** 从标题生成锚点 slug：词表 → 拉丁片段 → 短语提示 → 兜底 section-N */
function slugFor(heading, usedInFile, index) {
  const text = heading.trim();

  // 1) 原文或剥前缀后全词命中词表
  if (DICTIONARY[text]) return DICTIONARY[text];
  const stripped = stripPrefix(text);
  if (DICTIONARY[stripped]) return DICTIONARY[stripped];

  // 2) 标题中自带的英文单词（如 `轻量只读渲染（renderMode: markdown）`）
  const latinWords =
    text.match(/[a-zA-Z][a-zA-Z0-9-]*/g)?.map((w) => w.toLowerCase()) ?? [];
  // 3) 括号内的英文优先（通常是关键 API 名）
  const paren = text.match(/[（(]([^）)]*)[)）]/)?.[1];
  const latin =
    paren && /[a-zA-Z]/.test(paren)
      ? paren.match(/[a-zA-Z][a-zA-Z0-9-]*/g).map((w) => w.toLowerCase())
      : latinWords;

  const hints = [];
  for (const [re, hint] of PHRASE_HINTS) {
    if (re.test(stripped || text)) hints.push(hint);
  }

  let base;
  if (latin.length > 0) {
    base = [...hints.slice(0, 1), ...latin].join('-');
  } else if (hints.length > 0) {
    base = hints.slice(0, 2).join('-');
  } else {
    base = `section-${index}`;
  }
  base = base.replace(/-+/g, '-').replace(/^-|-$/g, '') || `section-${index}`;

  // 同文件去重
  if (!usedInFile.has(base)) return base;
  let n = 2;
  while (usedInFile.has(`${base}-${n}`)) n += 1;
  return `${base}-${n}`;
}

function processFile(filePath) {
  const raw = fs.readFileSync(filePath, 'utf8');
  // 统一按 \n 切分，保留原行结束符处理从简：docs 目前均为 LF 或 CRLF，
  // 写回时统一 LF（与仓库 .gitattributes/prettier 行为一致的风险极小，
  // 这里保守起见按原始内容是否含 \r\n 决定写回风格）
  const usesCRLF = raw.includes('\r\n');
  const lines = raw.split(/\r?\n/);
  const used = new Set();
  let changed = 0;

  const out = lines.map((line, i) => {
    const m = line.match(HEADING_RE);
    if (!m) return line;
    const [, hashes, text] = m;
    if (!hasHan(text)) return line;
    if (/\{#[a-zA-Z0-9_-]+\}\s*$/.test(text)) {
      used.add(text.match(/\{#([a-zA-Z0-9_-]+)\}\s*$/)[1]);
      return line;
    }
    // 代码块内的 "#" 行不是标题：粗略跳过（docs 中 fenced code 内标题极罕见，
    // 且 dumi 渲染同样不处理 code fence 内文本）
    const anchor = slugFor(text, used, i);
    used.add(anchor);
    changed += 1;
    return `${hashes} ${text} {#${anchor}}`;
  });

  if (changed > 0 && !DRY) {
    fs.writeFileSync(filePath, out.join(usesCRLF ? '\r\n' : '\n'), 'utf8');
  }
  return changed;
}

const docsDir = path.resolve('docs');
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name.endsWith('.md')) files.push(p);
  }
})(docsDir);

let total = 0;
let touched = 0;
for (const f of files) {
  const n = processFile(f);
  if (n > 0) {
    touched += 1;
    total += n;
  }
}
